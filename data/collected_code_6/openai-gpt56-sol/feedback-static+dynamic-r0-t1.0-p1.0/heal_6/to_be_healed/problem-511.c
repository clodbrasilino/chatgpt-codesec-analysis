int main(void)
{
    uint64_t value;
    uint64_t result;

    if (!read_uint64(&value)) {
        return EXIT_FAILURE;
    }

    if (!minimum_factor_sum(value, &result)) {
        return EXIT_FAILURE;
    }

    if (printf("%" PRIu64 "\n", result) < 0) {
        return EXIT_FAILURE;
    }

    return EXIT_SUCCESS;
}