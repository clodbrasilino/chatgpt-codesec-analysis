bool is_decimal_with_precision_2(const char *text)
{
    const unsigned char *p;

    if (text == NULL || *text == '\0') {
        return false;
    }

    p = (const unsigned char *)text;

    if (*p == '+' || *p == '-') {
        ++p;
    }

    if (!isdigit(*p)) {
        return false;
    }

    do {
        ++p;
    } while (isdigit(*p));

    if (*p++ != '.') {
        return false;
    }

    if (!isdigit(*p++)) {
        return false;
    }

    if (!isdigit(*p++)) {
        return false;
    }

    return *p == '\0';
}

