#include <stdio.h>
#include <string.h>

void replace_chars(char *str, size_t size) {
    size_t i = 0;
    while (i < size && str[i] != '\0') {
        if (str[i] == ' ' || str[i] == ',' || str[i] == '.') {
            str[i] = ':';
        }
        i++;
    }
}

