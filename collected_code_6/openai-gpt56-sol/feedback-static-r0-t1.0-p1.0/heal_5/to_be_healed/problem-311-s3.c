static uint32_t set_leftmost_unset_bit(uint32_t value)
{
    uint32_t mask = UINT32_C(1) << 31;

    while (mask != 0) {
        if ((value & mask) == 0) {
            return value | mask;
        }
        mask >>= 1;
    }

    return value;
}

